#include "stm32n657xx.h"
#include "phase_gpio.h"
#define P ((volatile uint32_t *)0x343C2000U)
enum { MAGIC,VERSION,STATE,ERROR,BEGIN,HOLD_BEGIN,HOLD_END,WFI_BEGIN,WFI_RETURNS,
 CCR,CONTROL,IPSR,PRIMASK,FAULTMASK,FPCCR,SYSTICK,SCR_BEFORE,SCR_AFTER,
 CFGR1,CFGR2,IC1,PLL1_1,PLL1_2,PLL1_3,BSEC_CLOCK,DEBUG_CLOCK,DEBUG_RESET,DEBUG_CR,
 APB5_CLOCK,APB5_RESET,DIVIDERS,CSI_SR0,DCMIPP_CMSR,PIPE0_CTL,PIPE0_CFG,
 PIPE1_CTL,PIPE1_CFG,PIPE2_CTL,PIPE2_CFG,SD_CLOCKS,SD_RESETS,
 ENABLE_BEFORE,PENDING_BEFORE,ENABLE_AFTER,PENDING_AFTER,NVIC_BANKS,
 NS_ENABLE_BEFORE,NS_PENDING_BEFORE,NS_ENABLE_AFTER,NS_PENDING_AFTER,
 GPIOO_CLOCK,GPIOO_MODE,GPIOO_ODR,GPIOO_IDR,DWT_CTRL,MSP,MSPLIM,
 APB5_AFTER,DIVIDERS_AFTER,SD_CLOCKS_AFTER,BSEC_AFTER,DEBUG_CR_AFTER,WORDS };
static __attribute__((noreturn,noinline)) void fail(uint32_t error)
{
 P[ERROR]=error;P[STATE]=15;__DSB();
 __asm volatile(".global power_sleep_refused\npower_sleep_refused:\nb.n .\n");
 __builtin_unreachable();
}
__attribute__((noreturn,used,noinline)) void power_sleep_entry(void)
{
 for(unsigned i=0;i<128;i++)P[i]=0;
 P[MAGIC]=0x31504C53;P[VERSION]=1;P[STATE]=1;P[BEGIN]=DWT->CYCCNT;
 P[CCR]=SCB->CCR;P[CONTROL]=__get_CONTROL();P[IPSR]=__get_IPSR();
 P[PRIMASK]=__get_PRIMASK();P[FAULTMASK]=__get_FAULTMASK();P[FPCCR]=FPU->FPCCR;
 P[SYSTICK]=SysTick->CTRL;P[MSP]=__get_MSP();P[MSPLIM]=__get_MSPLIM();
 if(P[CCR]&(SCB_CCR_IC_Msk|SCB_CCR_DC_Msk) ||P[CONTROL]||P[IPSR]||P[PRIMASK]!=1||
    P[FAULTMASK]||(P[FPCCR]&1)||P[SYSTICK]||P[MSPLIM]!=0x343AF000 ||
    P[MSP]<=0x343AF000 ||P[MSP]>0x343B0000)fail(1);
 P[CFGR1]=RCC->CFGR1;P[CFGR2]=RCC->CFGR2;P[IC1]=RCC->IC1CFGR;
 P[PLL1_1]=RCC->PLL1CFGR1;P[PLL1_2]=RCC->PLL1CFGR2;P[PLL1_3]=RCC->PLL1CFGR3;
 if(P[CFGR1]!=0x33330000||P[CFGR2]!=0x00100000||P[PLL1_1]!=0x00404B00||
    P[PLL1_2]||P[PLL1_3]!=0x49000005||
    (P[IC1]&(RCC_IC1CFGR_IC1INT|RCC_IC1CFGR_IC1SEL))!=0x20000)fail(2);
 P[BSEC_CLOCK]=RCC->APB4ENR2;P[DEBUG_CLOCK]=RCC->MISCENR;P[DEBUG_RESET]=RCC->MISCRSTR;
 if(!(P[BSEC_CLOCK]&RCC_APB4ENR2_BSECEN)||!(P[DEBUG_CLOCK]&RCC_MISCENR_DBGEN)||
    (P[DEBUG_RESET]&RCC_MISCRSTR_DBGRST))fail(3);
 P[DEBUG_CR]=DBGMCU->CR;
 /* No emulation-bit or clock changes: refuse if the current setup cannot
  * measure real shallow sleep under unchanged retained peripherals. */
 if(P[DEBUG_CR]&DBGMCU_CR_DBG_SLEEP)fail(4);
 P[DWT_CTRL]=DWT->CTRL;
 if(!(P[DWT_CTRL]&DWT_CTRL_CYCCNTENA_Msk)||!(CoreDebug->DEMCR&CoreDebug_DEMCR_TRCENA_Msk))fail(5);
 P[APB5_CLOCK]=RCC->APB5ENR;P[APB5_RESET]=RCC->APB5RSTR;P[DIVIDERS]=RCC->DIVENR;
 if((P[APB5_CLOCK]&(RCC_APB5ENR_CSIEN|RCC_APB5ENR_DCMIPPEN)) &&
    (P[APB5_CLOCK]&(RCC_APB5ENR_CSIEN|RCC_APB5ENR_DCMIPPEN))!=(RCC_APB5ENR_CSIEN|RCC_APB5ENR_DCMIPPEN))fail(6);
 if((P[APB5_CLOCK]&(RCC_APB5ENR_CSIEN|RCC_APB5ENR_DCMIPPEN)) &&
    !(P[APB5_RESET]&(RCC_APB5RSTR_CSIRST|RCC_APB5RSTR_DCMIPPRST))) {
  P[CSI_SR0]=CSI->SR0;P[DCMIPP_CMSR]=DCMIPP->CMSR1;
  P[PIPE0_CTL]=DCMIPP->P0FCTCR;P[PIPE0_CFG]=DCMIPP->P0FSCR;
  P[PIPE1_CTL]=DCMIPP->P1FCTCR;P[PIPE1_CFG]=DCMIPP->P1FSCR;
  P[PIPE2_CTL]=DCMIPP->P2FCTCR;P[PIPE2_CFG]=DCMIPP->P2FSCR;
  if((P[CSI_SR0]&(CSI_SR0_VC0STATEF|CSI_SR0_VC1STATEF|CSI_SR0_VC2STATEF|CSI_SR0_VC3STATEF))||
     (P[DCMIPP_CMSR]&(DCMIPP_CMSR1_P0CPTACT|DCMIPP_CMSR1_P1CPTACT|DCMIPP_CMSR1_P2CPTACT))||
     (P[PIPE0_CTL]&8)||(P[PIPE0_CFG]&0x80000000)||
     (P[PIPE1_CTL]&8)||(P[PIPE1_CFG]&0x80000000)||
     (P[PIPE2_CTL]&8)||(P[PIPE2_CFG]&0x80000000))fail(7);
 }
 P[SD_CLOCKS]=RCC->AHB5ENR;P[SD_RESETS]=RCC->AHB5RSTR;
 if(P[SD_CLOCKS]&RCC_AHB5ENR_SDMMC2EN)fail(8);
 P[GPIOO_CLOCK]=RCC->AHB4ENR;
 P[GPIOO_MODE]=P[GPIOO_ODR]=P[GPIOO_IDR]=0xffffffff;
 if((P[GPIOO_CLOCK]&RCC_AHB4ENR_GPIOOEN)&&!(RCC->AHB4RSTR&RCC_AHB4RSTR_GPIOORST)) {
  P[GPIOO_MODE]=GPIOO->MODER;P[GPIOO_ODR]=GPIOO->ODR;P[GPIOO_IDR]=GPIOO->IDR;
 }
 unsigned banks=(ICB->ICTR&ICB_ICTR_INTLINESNUM_Msk)+1;
 if(banks>16)fail(9);
 P[NVIC_BANKS]=banks;
 for(unsigned i=0;i<banks;i++) {
  P[ENABLE_BEFORE]|=NVIC->ISER[i];P[PENDING_BEFORE]|=NVIC->ISPR[i];
  P[NS_ENABLE_BEFORE]|=NVIC_NS->ISER[i];P[NS_PENDING_BEFORE]|=NVIC_NS->ISPR[i];
  NVIC->ICER[i]=0xffffffff;NVIC->ICPR[i]=0xffffffff;
  NVIC_NS->ICER[i]=0xffffffff;NVIC_NS->ICPR[i]=0xffffffff;
 }
 SCB->ICSR=SCB_ICSR_PENDSTCLR_Msk|SCB_ICSR_PENDSVCLR_Msk;
 SCB_NS->ICSR=SCB_ICSR_PENDSTCLR_Msk|SCB_ICSR_PENDSVCLR_Msk;
 __DSB();__ISB();
 for(unsigned i=0;i<banks;i++) {
  P[ENABLE_AFTER]|=NVIC->ISER[i];P[PENDING_AFTER]|=NVIC->ISPR[i];
  P[NS_ENABLE_AFTER]|=NVIC_NS->ISER[i];P[NS_PENDING_AFTER]|=NVIC_NS->ISPR[i];
 }
 if(P[ENABLE_AFTER]||P[PENDING_AFTER]||P[NS_ENABLE_AFTER]||P[NS_PENDING_AFTER])fail(10);
 P[SCR_BEFORE]=SCB->SCR;SCB->SCR&=~(SCB_SCR_SLEEPDEEP_Msk|SCB_SCR_SLEEPONEXIT_Msk|SCB_SCR_SEVONPEND_Msk);
 P[SCR_AFTER]=SCB->SCR;
 if(P[SCR_AFTER]&(SCB_SCR_SLEEPDEEP_Msk|SCB_SCR_SLEEPONEXIT_Msk|SCB_SCR_SEVONPEND_Msk))fail(11);
 if(!(RCC->AHB4ENR&RCC_AHB4ENR_GPIODEN)||(RCC->AHB4RSTR&RCC_AHB4RSTR_GPIODRST)||
    !phase_gpio_init()||!phase_gpio_emit(11))fail(12);
 P[STATE]=2;P[HOLD_BEGIN]=DWT->CYCCNT;
 uint32_t budget=100000000;
 while((uint32_t)(DWT->CYCCNT-P[HOLD_BEGIN])<80000000&&--budget)__NOP();
 P[HOLD_END]=DWT->CYCCNT;if(!budget||!phase_gpio_emit(12))fail(13);
 P[APB5_AFTER]=RCC->APB5ENR;P[DIVIDERS_AFTER]=RCC->DIVENR;
 P[SD_CLOCKS_AFTER]=RCC->AHB5ENR;P[BSEC_AFTER]=RCC->APB4ENR2;P[DEBUG_CR_AFTER]=DBGMCU->CR;
 if(P[APB5_AFTER]!=P[APB5_CLOCK]||P[DIVIDERS_AFTER]!=P[DIVIDERS]||
    P[SD_CLOCKS_AFTER]!=P[SD_CLOCKS]||P[BSEC_AFTER]!=P[BSEC_CLOCK]||P[DEBUG_CR_AFTER]!=P[DEBUG_CR])fail(14);
 P[WFI_BEGIN]=DWT->CYCCNT;P[STATE]=3;__DSB();__ISB();
 for(;;) {
  __asm volatile(".global power_sleep_wfi\npower_sleep_wfi:\nwfi\n":::"memory");
  P[WFI_RETURNS]++;
  __asm volatile(".global power_sleep_after_wfi\npower_sleep_after_wfi:\nnop\n");
 }
}
