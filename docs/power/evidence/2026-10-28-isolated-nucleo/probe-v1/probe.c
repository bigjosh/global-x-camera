#include "stm32n657xx.h"
#define Q ((volatile uint32_t *)0x343C1F00U)
#define P ((volatile uint32_t *)0x343C2000U)
#define B ((volatile uint32_t *)0x34310000U)
enum { MAGIC,VERSION,NONCE,STATE,ERROR,FLAGS,DIVIDER,CCR,CONTROL,IPSR,PRIMASK,
 FAULTMASK,FPCCR,VTOR_BEFORE,VTOR_ACTIVE,SCR_BEFORE,SCR_ACTIVE,SCR_AFTER,
 DBG_BEFORE,DBG_ACTIVE,DBG_AFTER,DEBUG_SAFE,CFGR1,CFGR2,IC1_BEFORE,IC1_ACTIVE,
 IC1_AFTER,PLL1_1,PLL1_2,PLL1_3,APB5_BEFORE,APB5_AFTER,AHB5_BEFORE,AHB5_AFTER,
 MEMENR_BEFORE,MEMENR_AFTER,MEMLPENR,AHB3LPENR,BUSLPENR,BSEC_CLOCK,BSEC_LPCLOCK,
 NVIC_ENABLE_BEFORE,NVIC_PENDING_BEFORE,NVIC_ENABLE_AFTER,NVIC_PENDING_AFTER,
 SYSTICK_BEFORE,SYSTICK_LOAD_BEFORE,SYSTICK_RELOAD,SYSTICK_FINAL,TICKS,
 PREFLIGHT_TICKS,BUSY_START,BUSY_END,BUSY_TICKS,BUSY_ITERATIONS,CHECKSUM,
 SLEEP_START,SLEEP_END,SLEEP_TICKS,WFI_CALLS,WFI_RETURNS,FINAL_PRIMASK,
 CFSR,HFSR,LED_ODR_BEFORE,LED_ODR_ACTIVE,LED_ODR_AFTER,PD12_ODR_AFTER,
 DWT_CTRL,DWT_PREFLIGHT,GPIO_SAFE,TERMINAL,WORDS };
extern void isolated_park(void) __attribute__((noreturn));
static void finish(uint32_t error) __attribute__((noreturn));
static void finish(uint32_t error)
{
 __disable_irq();SysTick->CTRL=0;SysTick->VAL=0;
 SCB->ICSR=SCB_ICSR_PENDSTCLR_Msk;
 if(P[DEBUG_SAFE]) {DBGMCU->CR=P[DBG_BEFORE];P[DBG_AFTER]=DBGMCU->CR;}
 SCB->SCR=P[SCR_BEFORE];P[SCR_AFTER]=SCB->SCR;
 P[IC1_AFTER]=RCC->IC1CFGR;P[APB5_AFTER]=RCC->APB5ENR;
 P[AHB5_AFTER]=RCC->AHB5ENR;P[MEMENR_AFTER]=RCC->MEMENR;
 P[NVIC_ENABLE_AFTER]=P[NVIC_PENDING_AFTER]=0;
 unsigned banks=(ICB->ICTR&15)+1;
 for(unsigned i=0;i<banks&&i<16;i++) {
  P[NVIC_ENABLE_AFTER]|=NVIC->ISER[i];P[NVIC_PENDING_AFTER]|=NVIC->ISPR[i];
 }
 P[SYSTICK_FINAL]=SysTick->CTRL;SysTick->LOAD=P[SYSTICK_LOAD_BEFORE];
 P[FINAL_PRIMASK]=__get_PRIMASK();P[CFSR]=SCB->CFSR;P[HFSR]=SCB->HFSR;
 if(P[GPIO_SAFE]) {P[LED_ODR_AFTER]=GPIOG->ODR;P[PD12_ODR_AFTER]=GPIOD->ODR;}
 P[ERROR]=error;P[STATE]=error?15:8;__DSB();P[TERMINAL]=0x454E4F44;__DSB();
 isolated_park();
}
void SysTick_Handler(void) { P[TICKS]++; }
void isolated_fault(void) { finish(0xF000U|__get_IPSR()); }
static void pulse(unsigned id)
{
 if(id<11||id>14)finish(30);
 GPIOD->BSRR=1U<<12;__DSB();uint32_t t=DWT->CYCCNT,n=10000;
 while((uint32_t)(DWT->CYCCNT-t)<id*800U&&--n)__NOP();
 GPIOD->BSRR=1U<<28;__DSB();if(!n)finish(31);
}
static void timer_start(void)
{
 __disable_irq();SysTick->CTRL=0;SysTick->LOAD=3999999;SysTick->VAL=0;
 SCB->ICSR=SCB_ICSR_PENDSTCLR_Msk;P[TICKS]=0;
 NVIC_SetPriority(SysTick_IRQn,0);SysTick->CTRL=7;__DSB();__ISB();__enable_irq();
}
static void timer_stop(void)
{
 __disable_irq();SysTick->CTRL=0;SCB->ICSR=SCB_ICSR_PENDSTCLR_Msk;__DSB();
}
void isolated_main(void)
{
 for(unsigned i=0;i<256;i++)P[i]=0;
 P[MAGIC]=0x314F5349;P[VERSION]=1;P[NONCE]=Q[1];P[STATE]=1;
 P[FLAGS]=Q[2];P[DIVIDER]=Q[3];
 P[SCR_BEFORE]=SCB->SCR;P[VTOR_ACTIVE]=SCB->VTOR;
 P[CCR]=SCB->CCR;P[CONTROL]=__get_CONTROL();P[IPSR]=__get_IPSR();
 P[PRIMASK]=__get_PRIMASK();P[FAULTMASK]=__get_FAULTMASK();P[FPCCR]=FPU->FPCCR;
 P[SYSTICK_BEFORE]=SysTick->CTRL;P[SYSTICK_LOAD_BEFORE]=SysTick->LOAD;
 if(Q[0]!=0x31514552||!Q[1]||Q[2]>1||Q[3]!=1||Q[4]||Q[5]||Q[6]||Q[7])finish(1);
 if(P[CCR]&0x30000||P[CONTROL]||P[IPSR]||P[PRIMASK]!=1||P[FAULTMASK]||
    (P[FPCCR]&1)||P[SYSTICK_BEFORE]||P[SCR_BEFORE]&6)finish(2);
 unsigned banks=(ICB->ICTR&15)+1;if(banks>16)finish(3);
 for(unsigned i=0;i<banks;i++) {
  P[NVIC_ENABLE_BEFORE]|=NVIC->ISER[i];P[NVIC_PENDING_BEFORE]|=NVIC->ISPR[i];
 }
 if(P[NVIC_ENABLE_BEFORE]||P[NVIC_PENDING_BEFORE])finish(4);
 P[CFGR1]=RCC->CFGR1;P[CFGR2]=RCC->CFGR2;P[IC1_BEFORE]=RCC->IC1CFGR;
 P[PLL1_1]=RCC->PLL1CFGR1;P[PLL1_2]=RCC->PLL1CFGR2;P[PLL1_3]=RCC->PLL1CFGR3;
 if(P[CFGR1]!=0x33330000||P[CFGR2]!=0x100000||P[PLL1_1]!=0x404b00||
    P[PLL1_2]||P[PLL1_3]!=0x49000005||
    (P[IC1_BEFORE]&(RCC_IC1CFGR_IC1SEL|RCC_IC1CFGR_IC1INT))!=0x20000)finish(5);
 P[IC1_ACTIVE]=RCC->IC1CFGR;
 P[APB5_BEFORE]=RCC->APB5ENR;P[AHB5_BEFORE]=RCC->AHB5ENR;P[MEMENR_BEFORE]=RCC->MEMENR;
 if((P[APB5_BEFORE]&(RCC_APB5ENR_CSIEN|RCC_APB5ENR_DCMIPPEN))||
    (P[AHB5_BEFORE]&RCC_AHB5ENR_SDMMC2EN))finish(6);
 P[MEMLPENR]=RCC->MEMLPENR;P[AHB3LPENR]=RCC->AHB3LPENR;P[BUSLPENR]=RCC->BUSLPENR;
 P[BSEC_CLOCK]=RCC->APB4ENR2;P[BSEC_LPCLOCK]=RCC->APB4LPENR2;
 uint32_t ram=RCC_MEMLPENR_AXISRAM1LPEN|RCC_MEMLPENR_AXISRAM2LPEN|RCC_MEMLPENR_AXISRAM3LPEN|
  RCC_MEMLPENR_AXISRAM4LPEN|RCC_MEMLPENR_AXISRAM5LPEN|RCC_MEMLPENR_AXISRAM6LPEN;
 uint32_t rif=RCC_AHB3LPENR_RIFSCLPEN|RCC_AHB3LPENR_RISAFLPEN;
 uint32_t bus=RCC_BUSLPENR_ACLKNLPEN|RCC_BUSLPENR_ACLKNCLPEN;
 if((P[MEMLPENR]&ram)!=ram||(P[AHB3LPENR]&rif)!=rif||(P[BUSLPENR]&bus)!=bus||
    !(P[BSEC_CLOCK]&RCC_APB4ENR2_BSECEN)||!(P[BSEC_LPCLOCK]&RCC_APB4LPENR2_BSECLPEN))finish(7);
 if(!(RCC->MISCENR&RCC_MISCENR_DBGEN)||(RCC->MISCRSTR&RCC_MISCRSTR_DBGRST))finish(8);
 P[DBG_BEFORE]=DBGMCU->CR;P[DEBUG_SAFE]=1;
 if(P[FLAGS]&1)DBGMCU->CR&=~DBGMCU_CR_DBG_SLEEP;
 P[DBG_ACTIVE]=DBGMCU->CR;
 if(P[DBG_ACTIVE]!=(P[DBG_BEFORE]&~((P[FLAGS]&1)?1U:0U)))finish(9);
 P[DWT_CTRL]=DWT->CTRL;
 if(!(P[DWT_CTRL]&1)||!(CoreDebug->DEMCR&CoreDebug_DEMCR_TRCENA_Msk))finish(10);
 uint32_t pins=RCC_AHB4ENR_GPIOGEN|RCC_AHB4ENR_GPIODEN;
 if((RCC->AHB4ENR&pins)!=pins||(RCC->AHB4RSTR&pins))finish(11);
 P[GPIO_SAFE]=1;
 if((GPIOG->MODER&0x00330003)!=0x00110001)finish(12);
 P[LED_ODR_BEFORE]=GPIOG->ODR;GPIOG->BSRR=0x501;P[LED_ODR_ACTIVE]=GPIOG->ODR;
 GPIOD->BSRR=1U<<28;GPIOD->OTYPER&=~(1U<<12);GPIOD->PUPDR&=~(3U<<24);
 GPIOD->OSPEEDR=(GPIOD->OSPEEDR&~(3U<<24))|(1U<<24);
 GPIOD->MODER=(GPIOD->MODER&~(3U<<24))|(1U<<24);
 SCB->SCR&=~0x16U;P[SCR_ACTIVE]=SCB->SCR;P[SYSTICK_RELOAD]=3999999;
 P[STATE]=2;timer_start();uint32_t t=DWT->CYCCNT,n=40000000;
 while(P[TICKS]<3&&(uint32_t)(DWT->CYCCNT-t)<40000000&&--n)__NOP();
 timer_stop();P[PREFLIGHT_TICKS]=P[TICKS];P[DWT_PREFLIGHT]=DWT->CYCCNT-t;
 if(P[PREFLIGHT_TICKS]!=3)finish(13);
 for(unsigned i=0;i<256;i++)B[i]=0x9e3779b9U*(i+1U);
 uint32_t x=0xA5F13579U,iterations=0;
 P[STATE]=3;pulse(11);timer_start();P[BUSY_START]=DWT->CYCCNT;t=DWT->CYCCNT;
 while(P[TICKS]<20) {
  for(unsigned i=0;i<256;i++) {x^=x<<13;x^=x>>17;x^=x<<5;B[i]^=x;x+=B[i];}
  iterations+=256;
  if((uint32_t)(DWT->CYCCNT-t)>160000000)finish(14);
 }
 timer_stop();P[BUSY_END]=DWT->CYCCNT;P[BUSY_TICKS]=P[TICKS];
 P[BUSY_ITERATIONS]=iterations;P[CHECKSUM]=x;pulse(12);
 P[STATE]=4;pulse(13);timer_start();P[SLEEP_START]=DWT->CYCCNT;
 while(P[TICKS]<20) {
  P[WFI_CALLS]++;__DSB();__WFI();P[WFI_RETURNS]++;
  if(P[WFI_CALLS]>1000)finish(15);
 }
 timer_stop();P[SLEEP_END]=DWT->CYCCNT;P[SLEEP_TICKS]=P[TICKS];pulse(14);
 P[STATE]=5;
 /* An IRQ between the while-condition and WFI can add one final timer tick;
  * it cannot cause an unbounded sleep because the periodic timer stays on. */
 if(P[BUSY_TICKS]<20||P[BUSY_TICKS]>21||P[SLEEP_TICKS]<20||P[SLEEP_TICKS]>21||
    !P[WFI_RETURNS]||P[WFI_RETURNS]!=P[WFI_CALLS])finish(16);
 finish(0);
}
