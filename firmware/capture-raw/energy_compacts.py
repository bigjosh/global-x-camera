"""Export/replay compact RAW-cycle energy using the unchanged v66c exporter.

Export validates raw arrays but archives no arrays. Replay requires only the
compact folder; it reproduces interval sums, not onset/plateau classification.
"""
import argparse
import gzip
import importlib.util
import json
import math
from pathlib import Path
import shutil
import statistics
import sys

from summarize_cycles import BASE, BASE_SHA, ENERGY_SHA, read, require, resolve, sha, write

PLOT_SHA='44e172b6c7ebed6bbb421285872d844bf98c403188f93f028704b1822b3e3682'
SEGMENTS=(('pretrigger_energy_j','integration_start_sample_id','current_onset_sample_id'),
    ('onset_to_plateau_energy_j','current_onset_sample_id','terminal_plateau_start_sample_id'),
    ('plateau_confirmation_energy_j','terminal_plateau_start_sample_id','integration_end_sample_id'),
    ('pretrigger_through_confirmed_plateau_energy_j','integration_start_sample_id','integration_end_sample_id'))


def modules(folder):
    for name,digest in (('cycle_energy',ENERGY_SHA),('cycle_plot',PLOT_SHA)):
        path=folder/'support'/(name+'.py')
        require(sha(path)==digest,'Frozen energy support changed: '+name)
        loader=importlib.util.spec_from_file_location(name,path)
        module=importlib.util.module_from_spec(loader);sys.modules[name]=module
        previous=sys.dont_write_bytecode
        try:
            sys.dont_write_bytecode=True
            loader.loader.exec_module(module)
        finally:
            sys.dont_write_bytecode=previous
    return sys.modules['cycle_plot']


def export(spec_path,analysis,out):
    spec_path=Path(spec_path).resolve();spec=read(spec_path);analysis=Path(analysis).resolve();out=Path(out).resolve()
    require(not out.exists(),'New compact output directory required')
    summary=read(analysis/'summary.json')
    require([v['name'] for v in spec['cycles']]==[v['name'] for v in summary['cycles']],
            'Cycle order differs from bound analysis')
    for p,digest in read(analysis/'manifest.json')['files'].items():
        path=(analysis/p).resolve()
        require(path.is_relative_to(analysis) and sha(path)==digest,'Analysis identity changed')
    require(sha(spec_path)==read(analysis/'manifest.json')['spec_sha256'],'Original spec differs')
    require(sha(BASE/'summary.json')==BASE_SHA,'Frozen baseline summary changed')
    out.mkdir(parents=True);(out/'support').mkdir()
    for name in ('cycle_energy.py','cycle_plot.py'):
        shutil.copyfile(BASE/'support'/name,out/'support'/name)
    shutil.copyfile(BASE/'summary.json',out/'v66c-summary.json')
    shutil.copyfile(analysis/'summary.json',out/'summary.json')
    plot=modules(out)
    for item in spec['cycles']:
        name=item['name'];source=resolve(spec_path.parent,item['recording']);dest=out/name;dest.mkdir()
        cycle=read(analysis/name/'energy.json');raw=read(source/'raw/manifest.json')
        require(sha(source/'raw/manifest.json')==read(source/'result.json')['raw_manifest_sha256'],
                'Raw recording binding changed')
        wrapped=dict(schema=1,uses_host_utc_alignment=False,sample_rate_hz=2000000,
            decimate_factor=1,manifest_sha256=sha(source/'raw/manifest.json'),cycles=[cycle])
        write(dest/'analysis.json',wrapped)
        shutil.copyfile(analysis/name/'context.json',dest/'context.json')
        shutil.copyfile(source/'raw/manifest.json',dest/'raw-manifest.json')
        (dest/'raw-chunks.jsonl.gz').write_bytes(gzip.compress((source/'raw/chunks.jsonl').read_bytes(),mtime=0))
        compact=plot.export(source/'raw',dest/'analysis.json')
        # Deterministic gzip wrapper around the unchanged exporter data model.
        payload=(json.dumps(compact,separators=(',',':'),allow_nan=False)+'\n').encode()
        (dest/'power-compact.json.gz').write_bytes(gzip.compress(payload,mtime=0))
        print(json.dumps(dict(cycle=name,rows=len(compact['rows']),
            bytes=(dest/'power-compact.json.gz').stat().st_size,integrals=compact['exact_segment_integrals_j'])),flush=True)
    (out/'README.md').write_text(
        '# Compact native-sample RAW-cycle energy\n\n'
        'Generated by the unchanged v66c exporter. Every finite sample in the selected '
        'view contributes to signed sums and extrema. Bins split exactly at current onset, '
        'plateau start and confirmation boundaries; no fractional-bin approximation is used.\n\n'
        'Run `python firmware/capture-raw/energy_compacts.py replay --folder PATH` without '
        'the original raw arrays. This reproduces the four energy intervals and primary '
        'durations/medians. It cannot rerun raw onset/plateau detection or recover within-bin '
        'sample order. SBF attribution and image readback remain separate evidence.\n\n'
        'The legacy 9.5 A validity threshold and recorded startup spikes are unchanged. '
        'No analog calibration, saturation correction, or isolated-DUT energy is inferred.\n',encoding='utf-8')
    write(out/'manifest.json',dict(schema=1,source_analysis_manifest_sha256=sha(analysis/'manifest.json'),
        files={p.relative_to(out).as_posix():sha(p) for p in sorted(out.rglob('*'))
               if p.is_file() and '__pycache__' not in p.parts and p.suffix!='.pyc'}))
    return replay(out)


def replay(folder):
    folder=Path(folder).resolve();manifest=read(folder/'manifest.json')
    for name,digest in manifest['files'].items():
        path=(folder/name).resolve()
        require(path.is_relative_to(folder) and sha(path)==digest,'Compact artifact identity changed: '+name)
    plot=modules(folder);summary=read(folder/'summary.json');baseline=read(folder/'v66c-summary.json')
    require(sha(folder/'v66c-summary.json')==BASE_SHA,'Baseline identity differs')
    results=[]
    for row in summary['cycles']:
        dest=folder/row['name'];wrapped=read(dest/'analysis.json');cycle,=wrapped['cycles']
        compact=plot.read_compact(dest/'power-compact.json.gz');raw=read(dest/'raw-manifest.json')
        require(compact['analysis_sha256']==sha(dest/'analysis.json') and
            compact['raw_manifest_sha256']==sha(dest/'raw-manifest.json') and
            compact['raw_files']==raw['files'] and compact['raw_chunks_sha256']==raw['chunks_sha256'] and
            compact['cycle_analysis']==cycle and raw['finalized'] and raw['status']['coverage']['passed'],
            'Compact/raw/analysis binding differs')
        import hashlib
        require(hashlib.sha256(gzip.decompress((dest/'raw-chunks.jsonl.gz').read_bytes())).hexdigest()==raw['chunks_sha256'],
                'Raw chunk metadata differs')
        require(sha(dest/'context.json')==cycle['terminal_evidence_sha256'],'Terminal attestation differs')
        require(compact['sample_rate_hz']==2000000 and compact['decimate_factor']==1,'Sample geometry differs')
        rows=compact['rows']
        require(all(len(r)==12 and r[2]==r[1]-r[0] and r[2]>0 and all(math.isfinite(v) for v in r) for r in rows),
                'Compact bin geometry or finite-data check failed')
        require(all(a[1]==b[0] for a,b in zip(rows,rows[1:])),'Compact coverage gap/overlap')
        terms={};bounds=compact['boundaries']
        for name,a,b in SEGMENTS:
            value=plot.integrated(rows,bounds[a],bounds[b],compact['sample_rate_hz'],compact['decimate_factor'])
            require(math.isclose(value,cycle[name],rel_tol=1e-12,abs_tol=1e-12) and
                math.isclose(value,compact['exact_segment_integrals_j'][name],rel_tol=1e-12,abs_tol=1e-12),
                'Integral differs: '+name)
            terms[name]=value
        seconds=(bounds['terminal_plateau_start_sample_id']-bounds['current_onset_sample_id'])/compact['sample_rate_hz']
        require(math.isclose(seconds,cycle['onset_to_plateau_s'],rel_tol=1e-12,abs_tol=1e-12),
                'Duration differs')
        require(row['onset_to_plateau_s']==cycle['onset_to_plateau_s'] and
            row['onset_to_plateau_energy_j']==cycle['onset_to_plateau_energy_j'],'Summary terms differ')
        results.append(dict(name=row['name'],onset_to_plateau_s=seconds,integrals_j=terms,
                            terminal_state_qualified=cycle['terminal_state_qualified']))
    for key,field in (('energy_j','onset_to_plateau_energy_j'),('current_onset_to_plateau_s','onset_to_plateau_s')):
        values=[r[field] for r in summary['cycles']]
        require(summary[key]==dict(n=len(values),median=statistics.median(values),minimum=min(values),maximum=max(values)),
                'Aggregate differs')
    require(summary['same_boundary_criteria']==baseline['same_boundary_criteria'],'Threshold criteria differ')
    return dict(schema=1,passed=True,cycles=len(results),replayed_energy_intervals=len(results)*4,results=results,
        limits=['Compact sums reproduce selected interval energies; raw boundary classification is not replayed.',
                'Original samples are not reconstructed; no per-phase energy or exact physical WFI timestamp is inferred.'])


def main():
    p=argparse.ArgumentParser(description=__doc__);sub=p.add_subparsers(dest='command',required=True)
    e=sub.add_parser('export');e.add_argument('--spec',type=Path,required=True)
    e.add_argument('--analysis',type=Path,required=True);e.add_argument('--out',type=Path,required=True)
    e.add_argument('--recorders-stopped',action='store_true')
    r=sub.add_parser('replay');r.add_argument('--folder',type=Path,required=True)
    a=p.parse_args()
    if a.command=='export':
        if not a.recorders_stopped:p.error('Confirm recorders stopped before raw hashing')
        result=export(a.spec,a.analysis,a.out)
    else: result=replay(a.folder)
    print(json.dumps(result,indent=2))


if __name__=='__main__':main()
