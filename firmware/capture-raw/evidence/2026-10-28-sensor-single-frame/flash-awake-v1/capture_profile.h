#ifndef CAPTURE_PROFILE_H
#define CAPTURE_PROFILE_H

#ifndef CAPTURE_DIAGNOSTICS
#define CAPTURE_DIAGNOSTICS 0
#endif
#if CAPTURE_DIAGNOSTICS != 0 && CAPTURE_DIAGNOSTICS != 1
#error "CAPTURE_DIAGNOSTICS must be 0 (normal) or 1 (diagnostic)"
#endif

/* LED1 occupies 0x343F89C0..0x343F8A40. Keep a 64-byte gap after it. */
#define CAPTURE_PROFILE_ADDRESS 0x343F8A80U
#define CAPTURE_PROFILE_MAGIC 0x52435032U
#define CAPTURE_PROFILE_SCHEMA 2U
#define CAPTURE_PROFILE_WORDS 32U
#define CAPTURE_PROFILE_REQUIRED_FLAGS 0x1FU
#define CAPTURE_PROFILE_DIAGNOSTIC_FLAGS 0x7FU

enum capture_profile_word {
    CP_MAGIC, CP_SCHEMA, CP_WORDS, CP_PROFILE, CP_STATE, CP_FLAGS,
    CP_FRAME, CP_BYTES, CP_WIDTH, CP_HEIGHT, CP_BITS, CP_DATA_TYPE,
    CP_FNV, CP_DMA_BYTES, CP_ERRORS, CP_CANARY_MASK,
    CP_POST_FRAME_BEGIN, CP_ESSENTIAL_DONE, CP_PIPE_STOP_BEGIN,
    CP_PIPE_STOP_DONE, CP_DATA_OFF_DONE, CP_SENSOR_STOP_DONE,
    CP_SCAN_BEGIN, CP_SCAN_DONE, CP_HANDOFF_READY,
    CP_DIAGNOSTIC_READS_BEGIN, CP_DIAGNOSTIC_READS_DONE
};
enum capture_profile_flag {
    CP_F_GEOMETRY=1U, CP_F_RAW10=2U, CP_F_CANARY=4U,
    CP_F_ERRORS=8U, CP_F_SAFE_STOP=16U, CP_F_FULL_SCAN=32U,
    CP_F_REGISTER_DUMPS=64U
};

#endif
