"""Record boot probes until a stop file appears, with a bounded timeout.

Starts a new capture in the existing Logic automation server. Does not change
target power or firmware. Create OUTPUT/stop when the physical experiment is
complete. Raw traces and boot analysis remain in the selected local directory.
"""

import argparse
import json
from pathlib import Path
import sys
import time

from analyze_capture import analyze


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('output', type=Path)
    parser.add_argument('--seconds', type=float, default=180)
    parser.add_argument('--ch5-signal', choices=['target-5v', 'main-vddio'], default='target-5v',
                        help='Record the physically connected CH5 probe in capture metadata.')
    args = parser.parse_args()
    if not 1 <= args.seconds <= 300:
        parser.error('--seconds must be between 1 and 300')
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=False)
    repo = Path(__file__).resolve().parents[2]
    sys.path.insert(0, str(repo / 'tmp/bringup/saleae-deps'))
    from saleae import automation
    config = {'digital_sample_rate': 6250000, 'analog_sample_rate': 31250,
              'digital_threshold_volts': 3.3, 'channels': list(range(6)),
              'maximum_duration_s': args.seconds,
              'channel_map': {'0': 'NRST', '1': 'PD0', '2': 'PE0',
                              '3': 'auxiliary 3.3 V', '4': 'target 5 V',
                              '5': args.ch5_signal},
              'mode': 'manual; no target stimulus generated by this program'}
    with automation.Manager.connect(port=10430, connect_timeout_seconds=5) as manager:
        devices = manager.get_devices()
        device = next((d for d in devices if d.device_id == '6753424D9C96677D' and not d.is_simulation), None)
        if device is None:
            raise RuntimeError('Required physical Logic Pro 8 was not found')
        config['device_id'] = device.device_id
        config['app_info'] = str(manager.get_app_info())
        # Preserve the probe map even if capture or export fails. This file
        # records requested settings; it is not evidence of a completed capture.
        (output / 'capture-config.json').write_text(
            json.dumps(config, indent=2) + '\n', encoding='utf-8')
        settings = automation.LogicDeviceConfiguration(
            enabled_digital_channels=list(range(6)), digital_sample_rate=6250000,
            digital_threshold_volts=3.3, enabled_analog_channels=list(range(6)),
            analog_sample_rate=31250)
        mode = automation.CaptureConfiguration(capture_mode=automation.ManualCaptureMode())
        with manager.start_capture(device_id=device.device_id, device_configuration=settings,
                                   capture_configuration=mode) as capture:
            (output / 'started').write_text('Capture running; create stop to finish.\n')
            print('CAPTURE_STARTED', output, flush=True)
            deadline = time.monotonic() + args.seconds
            try:
                while time.monotonic() < deadline and not (output / 'stop').exists():
                    time.sleep(0.1)
            finally:
                capture.stop()
                capture.save_capture(str(output / 'boot.sal'))
                capture.export_raw_data_csv(str(output), digital_channels=list(range(6)),
                                            analog_channels=list(range(6)))
    print('CAPTURE_SAVED', output, flush=True)
    analyze(output)


if __name__ == '__main__':
    main()
