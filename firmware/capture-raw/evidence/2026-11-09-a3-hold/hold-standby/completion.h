#ifndef CAPTURE_LOW_POWER_COMPLETION_H
#define CAPTURE_LOW_POWER_COMPLETION_H
#include <stdint.h>

/* These records are in AXI SRAM. Standby destroys them. Their existence proves
 * software preparation, never physical entry or persistence across reset. */
#define LOW_POWER_PROOF_ADDRESS 0x343F9C00U
#define LOW_POWER_PERIPHERAL_PROOF_ADDRESS 0x343F9D00U
#define LOW_POWER_PROOF_WORDS 64U
#define LOW_POWER_PROOF_MAGIC 0x4C504D31U /* LPM1 */
#define LOW_POWER_PROOF_TERMINAL 0x4C50454EU /* LPEN */

enum {
    LPC_MAGIC, LPC_SCHEMA, LPC_WORDS, LPC_MODE, LPC_STATE, LPC_ERROR,
    LPC_BEGIN_CYCLES, LPC_ARM_CYCLES, LPC_RETURN_CYCLES, LPC_DELAY_US,
    LPC_PERIPHERAL_RESULT, LPC_SCR, LPC_PRIMASK, LPC_SYSTICK_CTRL,
    LPC_NVIC_ENABLE_OR, LPC_NVIC_PENDING_OR, LPC_ICSR, LPC_CCR,
    LPC_PWR_CPUCR_BEFORE, LPC_PWR_CPUCR_AFTER, LPC_PWR_CR1, LPC_PWR_CR4,
    LPC_PWR_WKUPEPR, LPC_PWR_WKUPSR, LPC_RCC_STOPCR, LPC_RCC_APB4ENR2,
    LPC_RCC_AHB4ENR, LPC_RCC_RSR, LPC_DBG_CR_BEFORE, LPC_DBG_CR_AFTER,
    LPC_OTP124_SHADOWED, LPC_OTP124_VALID, LPC_OTP124_VALUE,
    LPC_EXTI_IMR_OR, LPC_EXTI_EMR_OR, LPC_EXTI_RPR_OR, LPC_EXTI_FPR_OR,
    LPC_GPIOG_ODR, LPC_CPU_HZ, LPC_PWR_CPUCR_RETURN, LPC_SCR_RETURN,
    LPC_CHECKSUM=62, LPC_TERMINAL=63
};
enum {
    LPC_STATE_BEGIN=10, LPC_STATE_PERIPHERALS_OFF=20, LPC_STATE_PREPARED=30,
    LPC_STATE_ARMED=40, LPC_STATE_RETURNED=50, LPC_STATE_REFUSED=255
};
enum {
    LPC_OK=0, LPC_ERROR_PERIPHERALS=1, LPC_ERROR_PWR_ACCESS=2,
    LPC_ERROR_BSEC_CLOCK=3, LPC_ERROR_OTP_UNKNOWN=4,
    LPC_ERROR_LOWPOWER_RESET_OPTION=5, LPC_ERROR_HARDWARE_IWDG=6,
    LPC_ERROR_DEBUG_ACCESS=7, LPC_ERROR_DEBUG_EMULATION=8,
    LPC_ERROR_PENDING_SOURCE=9, LPC_ERROR_MODE_READBACK=10,
    LPC_ERROR_UNEXPECTED_RETURN=11, LPC_ERROR_CPU_CONTEXT=12,
    LPC_ERROR_EXTERNAL_CORE_SUPPLY=13, LPC_ERROR_DELAY_CLOCK=14
};

/* Replaces the frozen receiver's sleep.c only for opt-in completion variants. */
__attribute__((noreturn)) void status_led_complete_sleep(void);
#endif
