"""Generate knob_tables.h: the exposure and analog-gain lookup tables.

The boot selector reads two potentiometers and converts each reading into a
sensor setting with these tables. Run this script to regenerate the header
after changing a constant below; test_knob.py fails if the committed header
differs from what this script produces.

Sensor timing (VD56G3 as configured by the capture prefix): 12 MHz clock,
PLL 804 MHz, VT clock divider 5, line length 1236. One line lasts
1236 * 5 / 804 MHz = 7.6866 microseconds, so the fixed 1428 lines used until
now are 10.98 ms.
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent

LINE_NS = 1236 * 5 * 1000 // 804          # 7686 ns per line, rounded down
DEFAULT_LINES = 1428                      # fixed exposure before the knobs
DEFAULT_FRAME = 4336                      # frame length the prefix programs
# The frame must outlast the exposure plus readout. max(4336, lines + 2000) is
# the rule the October long-exposure bench test used (30000 lines, frame 32000).
FRAME_MARGIN = 2000
FRAME_MAX = 65535                         # 16-bit sensor register

# The receiver is armed about 0.24 ms before the exposure starts (5.04 to
# 5.07 ms after sensor START in 37 recorded runs; the strobe rises at 5.29 ms),
# and readout begins 0.24 ms after the exposure ends. The floor therefore sets
# how long after arming the picture starts to arrive: about 1 ms here.
MIN_LINES = 65                            # 0.5 ms; the sensor driver's own floor is 21 lines
MAX_LINES = 63000                         # 484 ms; frame length 65000

STEPS = 32                                # table intervals across the knob travel
GAIN_CODE_MAX = 28                        # gain = 32 / (32 - code): 1x .. 8x

# Usable ADC code range. The Nucleo divides each header pin by 1030/560 into
# the 1.8 V converter, whose calibrated output tops out near 3839, and both
# knobs were observed to span about 0..3840. A dead band at each end makes
# both extremes reachable despite tolerances.
CODE_LOW = 120
CODE_HIGH = 3720


def movw_r1(value):
    """Thumb-2 "MOVW r1, #value" as stored in memory; mirrors knob_movw_r1()."""
    first = 0xF240 | (((value >> 11) & 1) << 10) | ((value >> 12) & 15)
    second = (((value >> 8) & 7) << 12) | (1 << 8) | (value & 255)
    return first.to_bytes(2, 'little') + second.to_bytes(2, 'little')


def manual_block(lines=DEFAULT_LINES, gain=0):
    """The twelve bytes the prefix writes to sensor register 0x044C onward:
    manual mode, analog gain code, exposure lines, four unity digital gains."""
    return bytes([2, gain, lines & 255, lines >> 8, 0, 1, 0, 1, 0, 1, 0, 1])


def exposure_table():
    ratio = MAX_LINES / MIN_LINES
    table = [round(MIN_LINES * ratio ** (k / STEPS)) for k in range(STEPS + 1)]
    table[0], table[-1] = MIN_LINES, MAX_LINES
    return table


def gain_table():
    # Equal photographic stops across the travel: gain = 8 ** x.
    table = [round(32 - 32 / 8 ** (k / STEPS)) for k in range(STEPS + 1)]
    table[0], table[-1] = 0, GAIN_CODE_MAX
    return table


def render():
    exposure, gain = exposure_table(), gain_table()
    assert all(b > a for a, b in zip(exposure, exposure[1:]))
    assert all(b >= a for a, b in zip(gain, gain[1:]))
    assert MIN_LINES >= 21 and MAX_LINES + FRAME_MARGIN <= FRAME_MAX

    def rows(values, per_line):
        chunks = [values[i:i + per_line] for i in range(0, len(values), per_line)]
        return ",\n".join("    " + ", ".join(str(v) for v in chunk) for chunk in chunks)

    return f"""/* Generated by knob_tables.py. Do not edit by hand. */
#ifndef USB_PTP_KNOB_TABLES_H
#define USB_PTP_KNOB_TABLES_H

#define KNOB_LINE_NS {LINE_NS}U
#define KNOB_DEFAULT_LINES {DEFAULT_LINES}U
#define KNOB_DEFAULT_FRAME {DEFAULT_FRAME}U
#define KNOB_FRAME_MARGIN {FRAME_MARGIN}U
#define KNOB_FRAME_MAX {FRAME_MAX}U
#define KNOB_MIN_LINES {MIN_LINES}U
#define KNOB_MAX_LINES {MAX_LINES}U
#define KNOB_STEPS {STEPS}U
#define KNOB_GAIN_CODE_MAX {GAIN_CODE_MAX}U
#define KNOB_CODE_LOW {CODE_LOW}U
#define KNOB_CODE_HIGH {CODE_HIGH}U

/* Exposure in sensor lines at each 1/{STEPS} of the knob travel. */
static const uint16_t knob_exposure_lines[KNOB_STEPS + 1U] = {{
{rows(exposure, 8)}
}};

/* Analog gain code at each 1/{STEPS} of the knob travel. */
static const uint8_t knob_gain_codes[KNOB_STEPS + 1U] = {{
{rows(gain, 11)}
}};

#endif
"""


if __name__ == "__main__":
    (HERE / "knob_tables.h").write_text(render(), encoding="utf-8", newline="\n")
    print("wrote", HERE / "knob_tables.h")
